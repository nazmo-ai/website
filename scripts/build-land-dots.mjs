/**
 * Generates the dot-matrix world map used behind the hero.
 *
 * Samples Natural Earth 110m land polygons on a fixed grid and writes the
 * land-covered points to `src/data/landDots.ts` as a base64-packed Int16Array.
 * The output is committed, so no geographic library ships to the browser.
 *
 * Run with: node scripts/build-land-dots.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)

/** Reference canvas width the dot coordinates are expressed in. */
const REF_WIDTH = 1600
/** Spacing between grid samples, in reference pixels. */
const SPACING = 8
/** Latitude clip — drops Antarctica, keeps Patagonia and New Zealand. */
const LAT_MAX = 78
const LAT_MIN = -56

const REF_HEIGHT = Math.round(((LAT_MAX - LAT_MIN) / 360) * REF_WIDTH)
const COLS = Math.floor(REF_WIDTH / SPACING)
const ROWS = Math.floor(REF_HEIGHT / SPACING)

/** Ray-casting point-in-ring test. Ring is an array of [lng, lat] pairs. */
function pointInRing(lng, lat, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside
    }
  }
  return inside
}

function ringBounds(ring) {
  let minX = Infinity
  let minY = Infinity
  let maxX = -Infinity
  let maxY = -Infinity
  for (const [x, y] of ring) {
    if (x < minX) minX = x
    if (x > maxX) maxX = x
    if (y < minY) minY = y
    if (y > maxY) maxY = y
  }
  return { minX, minY, maxX, maxY }
}

/** Flattens a (Multi)Polygon into [{ outer, holes, bounds }] with bounding boxes. */
function collectPolygons(geometry) {
  const raw =
    geometry.type === 'MultiPolygon' ? geometry.coordinates : [geometry.coordinates]

  return raw.map((rings) => {
    const [outer, ...holes] = rings
    return { outer, holes, bounds: ringBounds(outer) }
  })
}

function isLand(lng, lat, polygons) {
  for (const { outer, holes, bounds } of polygons) {
    if (lng < bounds.minX || lng > bounds.maxX || lat < bounds.minY || lat > bounds.maxY) {
      continue
    }
    if (!pointInRing(lng, lat, outer)) continue
    if (holes.some((hole) => pointInRing(lng, lat, hole))) continue
    return true
  }
  return false
}

const topology = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'))
const land = feature(topology, topology.objects.land)
const geometry = land.type === 'FeatureCollection' ? land.features[0].geometry : land.geometry
const polygons = collectPolygons(geometry)

const coords = []
for (let row = 0; row < ROWS; row++) {
  const lat = LAT_MAX - ((row + 0.5) / ROWS) * (LAT_MAX - LAT_MIN)
  for (let col = 0; col < COLS; col++) {
    const lng = -180 + ((col + 0.5) / COLS) * 360
    if (!isLand(lng, lat, polygons)) continue
    coords.push(Math.round(((lng + 180) / 360) * REF_WIDTH))
    coords.push(Math.round(((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * REF_HEIGHT))
  }
}

const packed = Buffer.from(new Int16Array(coords).buffer).toString('base64')

writeFileSync(
  new URL('../src/data/landDots.ts', import.meta.url),
  `// GENERATED by scripts/build-land-dots.mjs — do not edit by hand.
//
// ${coords.length / 2} land dots sampled from Natural Earth 110m land polygons
// on a ${SPACING}px grid, expressed in a ${REF_WIDTH}x${REF_HEIGHT} reference space.

/** Reference space the packed coordinates are expressed in. */
export const LAND_REF_WIDTH = ${REF_WIDTH}
export const LAND_REF_HEIGHT = ${REF_HEIGHT}

/** Latitude clip used by the projection. Must match \`project()\` in dotField.ts. */
export const LAT_MAX = ${LAT_MAX}
export const LAT_MIN = ${LAT_MIN}

export const LAND_DOT_COUNT = ${coords.length / 2}

const PACKED =
  '${packed}'

/** Decodes the packed grid into a flat [x0, y0, x1, y1, ...] array. */
export function decodeLandDots(): Int16Array {
  const binary = atob(PACKED)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return new Int16Array(bytes.buffer)
}
`,
)

console.log(`${coords.length / 2} land dots → src/data/landDots.ts (${REF_WIDTH}x${REF_HEIGHT})`)
